#!/usr/bin/env python3
"""Convert an image to a C array for the DK-E8 MIPI LCD (480x800, RGB888).

Usage:
    python3 img2c.py [input_image] [-o ../splash_img.c]

With no input image, a test card is generated: labeled red/green/blue
blocks make a swapped byte order obvious on the panel.
"""
import argparse
from PIL import Image, ImageDraw, ImageFont

WIDTH, HEIGHT = 480, 800


def font(size):
    for path in ("/System/Library/Fonts/Supplemental/Arial Bold.ttf",
                 "/System/Library/Fonts/Helvetica.ttc"):
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            pass
    return ImageFont.load_default()


def test_card():
    img = Image.new("RGB", (WIDTH, HEIGHT))
    d = ImageDraw.Draw(img)
    # vertical gradient background
    for y in range(HEIGHT):
        t = y / (HEIGHT - 1)
        d.line([(0, y), (WIDTH, y)], fill=(int(20 + 40 * t), int(30 + 60 * t), int(90 + 120 * t)))
    d.text((WIDTH // 2, 90), "Hello from", font=font(44), fill="white", anchor="mm")
    d.text((WIDTH // 2, 150), "Alif E8", font=font(72), fill="white", anchor="mm")
    d.text((WIDTH // 2, 215), "ExecuTorch Edge AI", font=font(30), fill=(200, 220, 255), anchor="mm")
    for i, (name, rgb) in enumerate((("RED", (230, 30, 30)),
                                     ("GREEN", (30, 200, 60)),
                                     ("BLUE", (40, 80, 240)))):
        top = 290 + i * 150
        d.rounded_rectangle([40, top, WIDTH - 40, top + 120], radius=18, fill=rgb)
        d.text((WIDTH // 2, top + 60), name, font=font(56), fill="white", anchor="mm")
    d.rectangle([0, 0, WIDTH - 1, HEIGHT - 1], outline="white", width=4)
    return img


def fit(img):
    """Letterbox the image onto a black 480x800 canvas."""
    img = img.convert("RGB")
    img.thumbnail((WIDTH, HEIGHT), Image.LANCZOS)
    canvas = Image.new("RGB", (WIDTH, HEIGHT))
    canvas.paste(img, ((WIDTH - img.width) // 2, (HEIGHT - img.height) // 2))
    return canvas


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("image", nargs="?")
    ap.add_argument("-o", "--output", default="splash_img.c")
    ap.add_argument("--preview", help="also save the final 480x800 image as PNG")
    args = ap.parse_args()

    img = fit(Image.open(args.image)) if args.image else test_card()
    if args.preview:
        img.save(args.preview)

    # CDC200 RGB888 is little-endian: bytes in memory are B, G, R.
    r, g, b = img.split()
    data = Image.merge("RGB", (b, g, r)).tobytes()

    with open(args.output, "w") as f:
        f.write("/* Generated by tools/img2c.py - 480x800 RGB888 (B,G,R byte order) */\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"const uint8_t splash_img[{len(data)}] __attribute__((aligned(16))) = {{\n")
        for i in range(0, len(data), 24):
            f.write(",".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",\n")
        f.write("};\n")
    print(f"wrote {args.output} ({len(data)} bytes)")


if __name__ == "__main__":
    main()
