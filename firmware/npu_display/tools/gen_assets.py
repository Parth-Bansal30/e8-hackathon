#!/usr/bin/env python3
"""Generate the C assets for npu_display.

  assets/fonts.h        8-bit alpha bitmap fonts (small ASCII + large digits)
  assets/test_digits.h  one MNIST test image per class 0..9 (0..127 pixels)

Usage: python3 tools/gen_assets.py   (run from the npu_display directory)
"""
import gzip
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "assets")
MNIST = os.path.join(HERE, "..", "..", "..", "model", "mnist_data")  # downloaded by model/export_mnist.py


def bitmap_font(name, path, size, first, last, index=0):
    font = ImageFont.truetype(path, size, index=index)
    ascent, descent = font.getmetrics()
    w = max(round(font.getlength(chr(c))) for c in range(first, last + 1))
    h = ascent + descent
    data = bytearray()
    for c in range(first, last + 1):
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((0, 0), chr(c), font=font, fill=255)
        data += img.tobytes()
    lines = [f"static const uint8_t {name}_data[{len(data)}] = {{"]
    for i in range(0, len(data), 32):
        lines.append(",".join(str(b) for b in data[i:i + 32]) + ",")
    lines.append("};")
    lines.append(f"static const font_t {name} = {{ {w}, {h}, {first}, {last}, {name}_data }};")
    return "\n".join(lines), (w, h)


def main():
    os.makedirs(ASSETS, exist_ok=True)

    small, s_wh = bitmap_font("font_small", "/System/Library/Fonts/Menlo.ttc", 24, 32, 126, index=1)
    large, l_wh = bitmap_font("font_large", "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
                              140, ord("0"), ord("9"))
    with open(os.path.join(ASSETS, "fonts.h"), "w") as f:
        f.write("/* Generated by tools/gen_assets.py */\n#pragma once\n#include <stdint.h>\n\n")
        f.write("typedef struct {\n    uint16_t w, h;\n    uint8_t first, last;\n"
                "    const uint8_t *data; /* w*h alpha bytes per glyph */\n} font_t;\n\n")
        f.write(small + "\n\n" + large + "\n")
    print(f"fonts.h: small {s_wh}, large {l_wh}")

    with gzip.open(os.path.join(MNIST, "t10k-images-idx3-ubyte.gz")) as f:
        images = f.read()[16:]
    with gzip.open(os.path.join(MNIST, "t10k-labels-idx1-ubyte.gz")) as f:
        labels = f.read()[8:]
    picks = [labels.index(d) for d in range(10)]  # first test image of each class
    with open(os.path.join(ASSETS, "test_digits.h"), "w") as f:
        f.write("/* Generated by tools/gen_assets.py: first MNIST test image of each class.\n"
                " * Pixels scaled 0..255 -> 0..127 like prepare_mnist_image.py. */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n#define NUM_TEST_DIGITS 10\n")
        f.write(f"static const uint16_t test_digit_index[10] = {{{','.join(map(str, picks))}}};\n")
        f.write(f"static const uint8_t test_digit_label[10] = {{{','.join(str(labels[i]) for i in picks)}}};\n")
        f.write("static const int8_t test_digits[10][784] = {\n")
        for i in picks:
            px = images[i * 784:(i + 1) * 784]
            f.write("  {" + ",".join(str(min(127, round(p * 127 / 255))) for p in px) + "},\n")
        f.write("};\n")
    print(f"test_digits.h: test indices {picks}")


if __name__ == "__main__":
    main()
