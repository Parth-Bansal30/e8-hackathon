#!/usr/bin/env python3
"""Quantize and export the DS-CNN keyword spotter for the Alif E8 Ethos-U85.

Same ExecuTorch Arm flow as export_mnist.py (int8 IO, whole graph on the NPU). Also writes
the C tables the board needs to compute identical features.

Usage (inside et-venv, after train_kws.py):
    python export_kws.py
    python export_kws.py --untrained       # check that the graph lowers, before training
Outputs: kws_ethos_u85.pte, kws_ethos_u85_io.h, ../firmware/app/kws_tables.h
"""
import argparse
import os
import sys

import numpy as np
import torch

import kws_common as K
from train_kws import CACHE, load, make_batch

HERE = os.path.dirname(os.path.abspath(__file__))


def write_tables(path):
    bands = K.mel_bands()
    weights = np.concatenate([w for _, w in bands])
    with open(path, "w") as f:
        f.write("/* Generated by model/export_kws.py: keyword-spotting feature constants.\n"
                " * Must match model/kws_common.py, or the model sees different inputs. */\n#pragma once\n")
        f.write(f"#define KWS_SR {K.SR}\n#define KWS_CLIP {K.CLIP}\n#define KWS_WIN {K.WIN}\n"
                f"#define KWS_HOP {K.HOP}\n#define KWS_FRAMES {K.FRAMES}\n#define KWS_NMEL {K.NMEL}\n"
                f"#define KWS_LOG_EPS ({K.LOG_EPS}f)\n#define KWS_FEAT_STD ({K.FEAT_STD}f)\n"
                f"#define KWS_NUM_LABELS {len(K.LABELS)}\n")
        f.write("static const char *const kws_labels[KWS_NUM_LABELS] = {"
                + ", ".join(f'"{l}"' for l in K.LABELS) + "};\n")
        f.write("static const unsigned short kws_mel_first[KWS_NMEL] = {"
                + ", ".join(str(b) for b, _ in bands) + "};\n")
        f.write("static const unsigned short kws_mel_len[KWS_NMEL] = {"
                + ", ".join(str(len(w)) for _, w in bands) + "};\n")
        f.write(f"static const float kws_mel_w[{len(weights)}] = {{\n")
        for i in range(0, len(weights), 8):
            f.write("    " + ", ".join(f"{v:.8e}f" for v in weights[i:i + 8]) + ",\n")
        f.write("};\n")
    print(f"wrote {path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default=os.path.join(HERE, "kws_model.pth"))
    ap.add_argument("--untrained", action="store_true")
    ap.add_argument("--calib", type=int, default=600)
    ap.add_argument("--eval", type=int, default=3000, help="test clips for the host accuracy check")
    ap.add_argument("--target", default="ethos-u85-256")
    ap.add_argument("--system_config", default="Ethos_U85_SYS_DRAM_Mid")
    ap.add_argument("--memory_mode", default="Shared_Sram")
    ap.add_argument("--out", default=os.path.join(HERE, "kws_ethos_u85.pte"))
    args = ap.parse_args()

    model = K.DSCNN()
    if not args.untrained:
        model.load_state_dict(torch.load(args.ckpt, map_location="cpu"))
    model = K.fold_batchnorm(model)
    feats = K.Features()

    rng = np.random.default_rng(7)
    if args.untrained:
        calib = [torch.randn(1, 1, K.FRAMES, K.NMEL) for _ in range(8)]
        xte = yte = None
    else:
        noise = np.load(os.path.join(CACHE, "noise.npy"))
        xva, yva = load("val")
        idx = rng.choice(len(yva), size=args.calib, replace=False)
        a, _ = make_batch(xva, yva, idx, noise, rng, False)
        with torch.no_grad():
            calib = list(feats(a).split(1))
        xte, yte = load("test")
        idx = rng.choice(len(yte), size=min(args.eval, len(yte)), replace=False)
        a, l = make_batch(xte, yte, idx, noise, rng, False)
        with torch.no_grad():
            xte, yte = feats(a), l

    def acc(fn):
        with torch.no_grad():
            p = torch.cat([fn(xte[i:i + 250]).argmax(1) for i in range(0, len(yte), 250)])
        return (p == yte).float().mean().item()

    if xte is not None:
        print(f"float32 (BN folded) accuracy: {acc(model):.4f} on {len(yte)} test clips")

    from executorch.backends.arm.ethosu import EthosUCompileSpec, EthosUPartitioner
    from executorch.backends.arm.quantizer import EthosUQuantizer, get_symmetric_quantization_config
    from executorch.exir import EdgeCompileConfig, ExecutorchBackendConfig, to_edge_transform_and_lower
    from executorch.exir.passes.quantize_io_pass import extract_io_quant_params
    from torchao.quantization.pt2e.quantize_pt2e import convert_pt2e, prepare_pt2e

    example = (calib[0],)
    spec = EthosUCompileSpec(args.target, system_config=args.system_config, memory_mode=args.memory_mode,
                             extra_flags=["--verbose-cycle-estimate"])
    graph = torch.export.export(model, example).module()
    quantizer = EthosUQuantizer(spec)
    quantizer.set_global(get_symmetric_quantization_config())
    prepared = prepare_pt2e(graph, quantizer)
    with torch.no_grad():
        for c in calib:
            prepared(c)
    q = convert_pt2e(prepared)
    if xte is not None:
        print(f"int8 (host sim) accuracy: {acc(q):.4f}")

    edge = to_edge_transform_and_lower(torch.export.export(q, example), partitioner=[EthosUPartitioner(spec)],
                                       compile_config=EdgeCompileConfig(_check_ir_validity=False))
    qp = extract_io_quant_params(edge, input_idxs=(0,), output_idxs=(0,))
    (in_q,), (out_q,) = qp["inputs"].values(), qp["outputs"].values()
    print(f"int8 IO: input scale={in_q['scale']} zp={in_q['zero_point']}  "
          f"output scale={out_q['scale']} zp={out_q['zero_point']}")
    prog = edge.to_executorch(config=ExecutorchBackendConfig(extract_delegate_segments=False))
    with open(args.out, "wb") as f:
        prog.write_to_file(f)
    print(f"wrote {args.out} ({os.path.getsize(args.out)} bytes)")

    hdr = os.path.splitext(args.out)[0] + "_io.h"
    with open(hdr, "w") as f:
        f.write("/* Generated by export_kws.py: int8 IO quantization of the KWS model */\n#pragma once\n")
        f.write(f"#define KWS_IN_SCALE  ({in_q['scale']:.9g}f)\n#define KWS_IN_ZP     ({in_q['zero_point']})\n")
        f.write(f"#define KWS_OUT_SCALE ({out_q['scale']:.9g}f)\n#define KWS_OUT_ZP    ({out_q['zero_point']})\n")
    print(f"wrote {hdr}")
    write_tables(os.path.join(HERE, "..", "firmware", "app", "kws_tables.h"))

    # Tell whether anything stayed on the CPU: the program should be a single delegate call.
    ops = [str(n.target) for n in edge.exported_program().graph.nodes if n.op == "call_function"]
    print("top-level ops after lowering:", sorted(set(ops)))


if __name__ == "__main__":
    sys.exit(main())
