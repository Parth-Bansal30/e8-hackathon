"""Make the Sound Sense UI fonts: signed-distance-field glyphs for gfx.c.

    python gen_font.py DejaVuSans-Bold.ttf DejaVuSans.ttf

Writes firmware/soundsense/ui/ui_fonts.c with ui_font_bold and ui_font_book. Each glyph is
rendered 8x larger than stored; the outline is found where the coverage crosses 50% (with
sub-pixel interpolation) and each stored pixel holds its signed distance to that outline.
Needs Pillow and numpy (both ship with matplotlib).

Characters: ASCII 32..126, plus 127 = middle dot and 128 = multiplication sign
(UI_DOT and UI_TIMES in ui_fonts.h).
"""
import math
import pathlib
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont

H = 40          # stored line height, px (ascent + descent)
PAD = 4         # blank margin around each glyph, px
SCALE = 24      # distance units per stored px: 128 +- 4 px covers the margin
SS = 8          # supersampling while rendering
CHARS = [chr(c) for c in range(32, 127)] + ["·", "×"]

OUT = pathlib.Path(__file__).resolve().parents[2] / "firmware/soundsense/ui/ui_fonts.c"


def load(path):
    """Font sized so ascent + descent = H * SS."""
    size = H * SS
    for _ in range(4):
        f = ImageFont.truetype(path, size)
        a, d = f.getmetrics()
        size = round(size * H * SS / (a + d))
    return ImageFont.truetype(path, size)


def glyph_sdf(font, ch):
    a, _ = font.getmetrics()
    adv = font.getlength(ch) / SS                    # stored px
    w = math.ceil(adv) + 2 * PAD
    hi = Image.new("L", (w * SS, (H + 2 * PAD) * SS), 0)
    ImageDraw.Draw(hi).text((PAD * SS, PAD * SS + a), ch, font=font, fill=255, anchor="ls")
    img = np.asarray(hi, dtype=np.float32)
    rows, cols = H + 2 * PAD, w
    # sample points: stored pixel centres, in hi-res pixel coordinates
    sy, sx = np.mgrid[0:rows, 0:cols]
    cx, cy = (sx + 0.5) * SS, (sy + 0.5) * SS
    inside = img[np.minimum(cy.astype(int), img.shape[0] - 1),
                 np.minimum(cx.astype(int), img.shape[1] - 1)] >= 128
    # outline points: where neighbouring hi-res pixels cross 128
    pts = []
    for a, b, axis in ((img[:, :-1], img[:, 1:], 1), (img[:-1, :], img[1:, :], 0)):
        yy, xx = np.nonzero((a >= 128) != (b >= 128))
        t = (128 - a[yy, xx]) / (b[yy, xx] - a[yy, xx])
        if axis == 1:
            pts.append(np.stack([xx + 0.5 + t, yy + 0.5], 1))
        else:
            pts.append(np.stack([xx + 0.5, yy + 0.5 + t], 1))
    pts = np.concatenate(pts)
    if len(pts) == 0:
        lo = np.full((rows, cols), -2.0 * PAD)
    else:
        s = np.stack([cx.ravel(), cy.ravel()], 1).astype(np.float32)
        d = np.empty(len(s), np.float32)
        for i in range(0, len(s), 256):
            diff = s[i:i + 256, None, :] - pts[None, :, :]
            d[i:i + 256] = np.sqrt((diff ** 2).sum(-1).min(1))
        lo = (d.reshape(rows, cols) / SS) * np.where(inside, 1.0, -1.0)   # stored px, + inside
    q = np.clip(np.rint(128 + lo * SCALE), 0, 255).astype(np.uint8)
    return q, w, round(adv * 16)


def emit(out, name, path):
    font = load(path)
    data, widths, offs, advs = bytearray(), [], [], []
    for ch in CHARS:
        q, w, adv = glyph_sdf(font, ch)
        offs.append(len(data))
        widths.append(w)
        advs.append(adv)
        data += q.tobytes()
    stem = pathlib.Path(path).name
    out.append(f"/* {stem}: {len(CHARS)} glyphs, {len(data)} bytes */")
    out.append(f"static const uint8_t {name}_w[] = {{{', '.join(map(str, widths))}}};")
    out.append(f"static const uint16_t {name}_adv[] = {{{', '.join(map(str, advs))}}};")
    out.append(f"static const uint32_t {name}_off[] = {{{', '.join(map(str, offs))}}};")
    out.append(f"static const uint8_t {name}_data[] = {{")
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const gfx_font {name} = {{{H}, 32, {31 + len(CHARS)}, 0, {name}_w, {name}_off, "
               f"{name}_data, {name}_adv, {PAD}, {SCALE}}};")
    out.append("")
    return len(data)


def main():
    bold, book = sys.argv[1], sys.argv[2]
    out = ["/* Generated by tools/ui_sim/gen_font.py. Do not edit.",
           " * DejaVu Sans fonts: see LICENSE-DejaVu.txt in this folder. */",
           '#include "ui_fonts.h"', ""]
    n = emit(out, "ui_font_bold", bold) + emit(out, "ui_font_book", book)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({n / 1024:.0f} KB of glyphs)")


if __name__ == "__main__":
    main()
